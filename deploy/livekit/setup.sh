#!/usr/bin/env bash
# NET360 Classroom — your own LiveKit audio server, on one small Ubuntu VPS.
#
#   1. Point a subdomain (e.g. audio.yourdomain.com) at this server's IP (DNS "A" record).
#   2. Copy this folder to the server and run:   sudo bash setup.sh audio.yourdomain.com
#   3. Paste the three lines it prints into Railway → Variables.
#
# Safe to run again: keeps the same keys, updates the config, restarts the services.
set -euo pipefail

DOMAIN="${1:-}"
if [[ -z "$DOMAIN" ]]; then
  echo "Usage: sudo bash setup.sh audio.yourdomain.com" >&2
  exit 1
fi
if [[ $EUID -ne 0 ]]; then
  echo "Please run with sudo." >&2
  exit 1
fi

DIR=/opt/net360-livekit
mkdir -p "$DIR"
cd "$DIR"

echo "==> Installing Docker (if needed)"
if ! command -v docker >/dev/null 2>&1; then
  curl -fsSL https://get.docker.com | sh
fi
systemctl enable --now docker >/dev/null

echo "==> Opening the firewall ports LiveKit needs"
if command -v ufw >/dev/null 2>&1; then
  ufw allow 22/tcp >/dev/null          # SSH (so you don't lock yourself out)
  ufw allow 80/tcp >/dev/null          # certificate check
  ufw allow 443/tcp >/dev/null         # secure connection for browsers
  ufw allow 7881/tcp >/dev/null        # media over TCP (strict networks)
  ufw allow 3478/udp >/dev/null        # TURN (helps students behind strict Wi-Fi)
  ufw allow 50000:60000/udp >/dev/null # media
  ufw allow 30000:40000/udp >/dev/null # TURN relay
  ufw --force enable >/dev/null
fi

echo "==> Keys"
if [[ -f .env ]]; then
  # shellcheck disable=SC1091
  source .env
else
  LIVEKIT_API_KEY="API$(openssl rand -hex 6)"
  LIVEKIT_API_SECRET="$(openssl rand -base64 36 | tr -d '/+=' | cut -c1-44)"
  printf 'LIVEKIT_API_KEY=%s\nLIVEKIT_API_SECRET=%s\n' "$LIVEKIT_API_KEY" "$LIVEKIT_API_SECRET" > .env
  chmod 600 .env
fi

echo "==> Writing configuration"
cat > livekit.yaml <<YAML
# NET360 Classroom — LiveKit (audio). Generated by setup.sh.
port: 7880
bind_addresses:
  - "127.0.0.1"          # only Caddy (HTTPS) talks to this port
rtc:
  tcp_port: 7881
  port_range_start: 50000
  port_range_end: 60000
  use_external_ip: true  # discover this server's public IP
turn:
  enabled: true
  udp_port: 3478
keys:
  ${LIVEKIT_API_KEY}: ${LIVEKIT_API_SECRET}
room:
  empty_timeout: 300
  max_participants: 200
logging:
  level: info
YAML
chmod 600 livekit.yaml

cat > Caddyfile <<CADDY
# HTTPS for the LiveKit server (certificate from Let's Encrypt, renewed automatically).
${DOMAIN} {
  reverse_proxy 127.0.0.1:7880
}
CADDY

cat > docker-compose.yml <<'YAML'
services:
  livekit:
    image: livekit/livekit-server:v1.13.11
    command: --config /etc/livekit.yaml
    network_mode: host
    restart: unless-stopped
    volumes:
      - ./livekit.yaml:/etc/livekit.yaml:ro
  caddy:
    image: caddy:2-alpine
    network_mode: host
    restart: unless-stopped
    volumes:
      - ./Caddyfile:/etc/caddy/Caddyfile:ro
      - caddy_data:/data
      - caddy_config:/config
volumes:
  caddy_data:
  caddy_config:
YAML

echo "==> Starting LiveKit"
docker compose pull -q
docker compose up -d

echo "==> Waiting for the secure address to come up (first time can take a minute)"
for i in $(seq 1 40); do
  if curl -fsS -m 5 "https://${DOMAIN}" >/dev/null 2>&1; then OK=1; break; fi
  sleep 3
done
echo
if [[ "${OK:-}" == "1" ]]; then
  echo "LiveKit is running at https://${DOMAIN}"
else
  echo "LiveKit started, but https://${DOMAIN} isn't answering yet."
  echo "Check that ${DOMAIN} points to this server's IP, then run:  docker compose -f ${DIR}/docker-compose.yml logs caddy"
fi
cat <<DONE

Add these to Railway → your service → Variables, then let it redeploy:

  LIVEKIT_URL=wss://${DOMAIN}
  LIVEKIT_API_KEY=${LIVEKIT_API_KEY}
  LIVEKIT_API_SECRET=${LIVEKIT_API_SECRET}

Then open  https://<your-railway-app>/api/health  — it should say "audio": true.
Keys are saved in ${DIR}/.env (keep them private).
DONE
